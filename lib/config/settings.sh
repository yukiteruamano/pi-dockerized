#!/bin/bash

# settings.sh - config file creation, loading, saving and key/value editing.
# Sourced by lib/config-lib.sh (not executable directly).
# shellcheck disable=SC2034 # globals are defined here and consumed by the other sourced modules
# NOTE: no "set -e" — library file; callers control their own error handling.
#
# The config is INI-style: `setting.<key>=<value>` and `mount.<name>=<spec>`.
# Every setting is described once in _setting_spec; the loader, `config set`
# and the saver all go through it, so validation cannot drift between them.

# Every setting key, in the order they are written to a fresh file.
SETTING_KEYS=(
    ssh_agent_support gpg_agent_support gpg_allow_main_socket gpg_autostart_agent
    gpg_relay docker_socket network security_policy allowed_tools verify_updates
    memory cpus env_file theme model
)

# ============================================
# CONFIG FILE OPERATIONS
# ============================================

# Check if config file exists
config_exists() {
    [ -f "$CONFIG_FILE" ]
}

# Initialize config file with header
init_config_file() {
    mkdir -p "$CONFIG_DIR"
    cat >"$CONFIG_FILE" <<'EOF'
# Pi Dockerized User Configuration
# Generated by 'pi-dockerized install' - edit manually, use
# 'pi-dockerized config set <key> <value>' or re-run 'pi-dockerized install'.
# Values are taken verbatim: do not add inline comments after a value.

# Settings
# SSH Agent Forwarding (enables git over SSH in container)
# Automatically mounts SSH_AUTH_SOCK socket and passes the environment variable
# setting.ssh_agent_support=false

# GnuPG Agent Forwarding (enables git commit signing with your host keys)
# Shares only the public keyring and the gpg-agent socket; private keys never
# enter the container. Requires a running gpg-agent on the host.
# setting.gpg_agent_support=false

# Allow falling back to the full-control gpg-agent socket when the restricted
# S.gpg-agent.extra socket is unavailable. NOT recommended: the main socket can
# reconfigure the host agent. Default: false (warn and skip instead).
# setting.gpg_allow_main_socket=false

# Launch the host gpg-agent automatically at run time when its socket is
# missing. Default: true. Set to false to only warn and never start it.
# setting.gpg_autostart_agent=true

# Relay the agent socket through a socket on a normal filesystem. Needed when
# socketdir is on tmpfs (/run/user/<uid>/gnupg), which Docker cannot bind.
# Requires `socat` on the host. Default: true.
# setting.gpg_relay=true

# Docker socket (opt-in). Mounting it grants the container full control of the
# host Docker daemon, which is effectively root on the host. Enable only when
# you need Docker-in-Docker / Testcontainers. Rebuild the image afterwards
# ('pi-dockerized build') so it contains the Docker CLI.
# setting.docker_socket=false

# Container network: host (default, simple; shares the host network namespace)
# or bridge (more isolated; host services are reached via host.docker.internal).
# setting.network=host

# Security policy mode enforced by the baked security-guard extension.
# strict = every vendored pattern, and tools outside the built-in set are
# refused unless listed in allowed_tools; balanced = drop the noisy false
# positives (default); off = vendored patterns disabled (backstops stay).
# setting.security_policy=balanced

# Comma-separated tool names that strict mode lets through besides Pi's own
# (bash, read, write, ...), e.g. an MCP tool. Ignored in balanced/off.
# setting.allowed_tools=

# Require `update` to verify the upstream commit signature (git verify-commit)
# before pulling. Needs the maintainer's key in your GnuPG keyring.
# setting.verify_updates=false

# Optional container resource limits (docker --memory / --cpus). Empty = no limit.
# setting.memory=4g
# setting.cpus=2

# Secrets file (dotenv KEY=VALUE lines) loaded with docker --env-file.
# Must live under ~/.config/pi-dockerized/ (never mounted). Create it with
# `install -m 600 /dev/null ~/.config/pi-dockerized/env` and add provider keys
# like ANTHROPIC_API_KEY=... Empty = disabled.
# setting.env_file=~/.config/pi-dockerized/env

# TUI theme (built-in, e.g. system). Empty = Pi default.
# setting.theme=system

# Startup model selection (passed as `pi --model`). Empty = Pi default.
# setting.model=sonnet

# Custom volume mounts (read-only by default)
# Format: mount.<name>=<host_path>:<container_path>[:rw]
# Examples:
#   mount.gitconfig=~/.gitconfig:/home/coder/.gitconfig
#   mount.gitignore_global=~/.config/git/gitignore_global:/home/coder/.config/git/gitignore_global
# NOTE: the home directory, ~/.ssh, ~/.gnupg and other credential stores, the
# wrapper's own config directory and the Docker socket are refused. Use
# setting.ssh_agent_support=true for SSH: the agent socket plus ~/.ssh/config
# and known_hosts are mounted read-only automatically.

# Secrets live in setting.env_file (dotenv KEY=VALUE, never mounted).
# Use `pi-dockerized install` to add keys without ever printing them.
EOF
    chmod 600 "$CONFIG_FILE" 2>/dev/null || true
    config_success "Created config file at $CONFIG_FILE"
}

# ============================================
# SETTING DEFINITIONS
# ============================================

# Describe one setting as "<VARIABLE> <type> <arg> <default>".
#   bool  true|false
#   enum  comma-separated choices in <arg>; empty value resets to <default>
#   re    value must match the ERE in <arg> (empty must match to be accepted)
#   any   verbatim
# Returns 1 for an unknown key.
_setting_spec() {
    case "$1" in
    ssh_agent_support) echo "SSH_AGENT_SUPPORT bool" ;;
    gpg_agent_support) echo "GPG_AGENT_SUPPORT bool" ;;
    gpg_allow_main_socket) echo "GPG_ALLOW_MAIN_SOCKET bool" ;;
    gpg_autostart_agent) echo "GPG_AUTOSTART_AGENT bool" ;;
    gpg_relay) echo "GPG_RELAY bool" ;;
    docker_socket) echo "DOCKER_SOCKET bool" ;;
    verify_updates) echo "VERIFY_UPDATES bool" ;;
    network) echo "NETWORK enum host,bridge host" ;;
    security_policy) echo "SECURITY_POLICY enum strict,balanced,off balanced" ;;
    allowed_tools) echo "ALLOWED_TOOLS re ^[A-Za-z0-9_.:,-]*$" ;;
    memory) echo "MEMORY re ^([0-9]+[bBkKmMgG])?$" ;;
    cpus) echo "CPUS re ^([0-9]+(\\.[0-9]+)?)?$" ;;
    theme) echo "THEME re ^[A-Za-z0-9_-]*$" ;;
    model) echo "MODEL re ^[A-Za-z0-9._:/@-]*$" ;;
    env_file) echo "ENV_FILE any" ;;
    *) return 1 ;;
    esac
}

# Reset every setting and mount to its default (before loading a file).
reset_settings() {
    CUSTOM_MOUNTS=()
    CUSTOM_MOUNT_KEYS=()
    SSH_AGENT_SUPPORT=false
    GPG_AGENT_SUPPORT=false
    GPG_ALLOW_MAIN_SOCKET=false
    GPG_AUTOSTART_AGENT=true
    GPG_RELAY=true
    DOCKER_SOCKET=false
    VERIFY_UPDATES=false
    NETWORK="host"
    SECURITY_POLICY="balanced"
    ALLOWED_TOOLS=""
    MEMORY=""
    CPUS=""
    ENV_FILE=""
    THEME=""
    MODEL=""
}

# Validate <value> for setting <key> and assign it to its variable.
# Returns 0 (applied), 1 (invalid, warned, variable untouched), 2 (unknown key).
# Usage: _apply_setting <key> <value>
_apply_setting() {
    local key="$1" value="$2" spec var type arg default
    spec=$(_setting_spec "$key") || return 2
    read -r var type arg default <<<"$spec"
    case "$type" in
    bool)
        case "$value" in
        true | false) ;;
        *)
            config_warning "Invalid value '$value' for setting.$key (use true|false); keeping '${!var}'"
            return 1
            ;;
        esac
        ;;
    enum)
        if [ -z "$value" ]; then
            value="$default"
        else
            case ",$arg," in
            *",$value,"*) ;;
            *)
                config_warning "Invalid value '$value' for setting.$key (use ${arg//,/|}); keeping '${!var}'"
                return 1
                ;;
            esac
        fi
        ;;
    re)
        if ! [[ "$value" =~ $arg ]]; then
            config_warning "Invalid value '$value' for setting.$key (unexpected format); keeping '${!var}'"
            return 1
        fi
        ;;
    esac
    printf -v "$var" '%s' "$value"
}

# Print the current value of setting <key>; returns 1 for an unknown key.
# Usage: _get_setting <key>
_get_setting() {
    local spec var
    spec=$(_setting_spec "$1") || return 1
    var="${spec%% *}"
    printf '%s' "${!var}"
}

# Trim leading/trailing whitespace of the variable named by $1, in place.
_trim() {
    local -n __trim_ref="$1"
    __trim_ref="${__trim_ref#"${__trim_ref%%[![:space:]]*}"}"
    __trim_ref="${__trim_ref%"${__trim_ref##*[![:space:]]}"}"
}

# ============================================
# LOADING AND SAVING
# ============================================

# Load the config file in one pass, preserving each mount's original key suffix
# so save_config can re-emit it unchanged. Unknown settings and malformed lines
# are reported with their line number, never silently ignored.
load_config() {
    if ! config_exists; then
        config_warning "Config file not found at $CONFIG_FILE"
        return 1
    fi

    reset_settings

    local key value lineno=0 rc
    while IFS='=' read -r key value || [ -n "$key" ]; do
        lineno=$((lineno + 1))
        _trim key
        _trim value
        case "$key" in
        "" | \#*) continue ;;
        mount.*)
            key="${key#mount.}"
            if [ -n "$value" ] && [ -n "$key" ]; then
                CUSTOM_MOUNT_KEYS+=("$key")
                CUSTOM_MOUNTS+=("$value")
            fi
            ;;
        env.*)
            # The host-environment passthrough was removed; secrets now live in
            # setting.env_file (see migrate_legacy_env_vars).
            [ -n "$value" ] && config_warning "Ignoring legacy '${key#env.}' (env.* passthrough was removed); move the value to setting.env_file instead."
            ;;
        setting.*)
            _apply_setting "${key#setting.}" "$value"
            rc=$?
            if [ "$rc" -eq 2 ]; then
                config_warning "config line $lineno: unknown setting '${key#setting.}' (ignored)"
            fi
            ;;
        *)
            config_warning "config line $lineno: unrecognized entry '$key' (ignored)"
            ;;
        esac
    done <"$CONFIG_FILE"

    return 0
}

# Allocate an unused "customN" key suffix for a new entry, avoiding collisions
# with already-used suffixes passed as arguments.
# Usage: key=$(next_custom_key "${CUSTOM_MOUNT_KEYS[@]}")
next_custom_key() {
    local n=1 existing
    while :; do
        local taken=false
        for existing in "$@"; do
            if [ "$existing" = "custom$n" ]; then
                taken=true
                break
            fi
        done
        if [ "$taken" = false ]; then
            echo "custom$n"
            return 0
        fi
        n=$((n + 1))
    done
}

# Set <full_key>=<value> in the config file, in place. The first active line is
# updated (later duplicates dropped); otherwise the first commented template
# `# <full_key>=...` becomes the active line; otherwise the line is appended.
# Comments and entries it does not know about are left alone.
# Usage: config_upsert <full_key> <value>
config_upsert() {
    local full="$1" value="$2"
    local -a lines=() out=()
    [ -f "$CONFIG_FILE" ] && mapfile -t lines <"$CONFIG_FILE"

    local i trimmed commented active=-1 template=-1
    for i in "${!lines[@]}"; do
        trimmed="${lines[$i]#"${lines[$i]%%[![:space:]]*}"}"
        case "$trimmed" in
        "$full="*)
            [ "$active" -lt 0 ] && active=$i
            ;;
        \#*)
            commented="${trimmed#\#}"
            commented="${commented#"${commented%%[![:space:]]*}"}"
            case "$commented" in
            "$full="*) [ "$template" -lt 0 ] && template=$i ;;
            esac
            ;;
        esac
    done

    local seen=false
    for i in "${!lines[@]}"; do
        trimmed="${lines[$i]#"${lines[$i]%%[![:space:]]*}"}"
        if [ "$i" -eq "$active" ] || { [ "$active" -lt 0 ] && [ "$i" -eq "$template" ]; }; then
            out+=("$full=$value")
            seen=true
        elif [[ "$trimmed" == "$full="* ]]; then
            continue # duplicate of an active line
        else
            out+=("${lines[$i]}")
        fi
    done
    [ "$seen" = true ] || out+=("$full=$value")

    printf '%s\n' "${out[@]}" >"$CONFIG_FILE"
}

# Replace every active mount.* line with the current CUSTOM_MOUNTS, dropping
# exact duplicates (idempotent across re-runs).
_config_rewrite_mounts() {
    local -a lines=() out=()
    [ -f "$CONFIG_FILE" ] && mapfile -t lines <"$CONFIG_FILE"

    local line trimmed
    for line in "${lines[@]}"; do
        trimmed="${line#"${line%%[![:space:]]*}"}"
        [[ "$trimmed" == mount.* ]] || out+=("$line")
    done

    local i entry seen="" any=false
    for i in "${!CUSTOM_MOUNTS[@]}"; do
        entry="mount.${CUSTOM_MOUNT_KEYS[$i]}=${CUSTOM_MOUNTS[$i]}"
        [[ "$seen" == *"|$entry|"* ]] && continue
        seen="$seen|$entry|"
        out+=("$entry")
        any=true
    done
    [ "$any" = true ] || [ "${#out[@]}" -gt 0 ] || return 0

    printf '%s\n' "${out[@]}" >"$CONFIG_FILE"
}

# Write the current settings and mounts to the config file, keeping its
# comments and any entries this version does not know about.
save_config() {
    mkdir -p "$CONFIG_DIR"
    config_exists || init_config_file >/dev/null

    local key
    for key in "${SETTING_KEYS[@]}"; do
        config_upsert "setting.$key" "$(_get_setting "$key")"
    done
    _config_rewrite_mounts

    config_success "Saved configuration to $CONFIG_FILE"
}

# ============================================
# KEY/VALUE ACCESS (config get / config set)
# ============================================

# Strip an optional "setting." prefix from a user-supplied key.
_setting_key() {
    printf '%s' "${1#setting.}"
}

# Print the value of a setting from the config file.
# Usage: config_get_value <key>
config_get_value() {
    local key
    key=$(_setting_key "$1")
    if ! _setting_spec "$key" >/dev/null; then
        config_error "Unknown setting '$key'. Known: ${SETTING_KEYS[*]}"
        return 1
    fi
    load_config >/dev/null 2>&1 || true
    _get_setting "$key"
    echo
}

# Validate and persist one setting.
# Usage: config_set_value <key> <value>
config_set_value() {
    local key value="$2"
    key=$(_setting_key "$1")
    if [[ "$value" == *$'\n'* ]]; then
        config_error "A value cannot contain a newline."
        return 1
    fi
    # Validate in a subshell so a rejected value never leaks into the globals.
    local rc=0
    (_apply_setting "$key" "$value") || rc=$?
    case "$rc" in
    0) ;;
    2)
        config_error "Unknown setting '$key'. Known: ${SETTING_KEYS[*]}"
        return 1
        ;;
    *)
        config_error "Not saved: invalid value for setting.$key."
        return 1
        ;;
    esac
    mkdir -p "$CONFIG_DIR"
    config_exists || init_config_file >/dev/null
    config_upsert "setting.$key" "$value"
    config_success "setting.$key=$value"
}
